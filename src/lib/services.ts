export function getService(slug: string): ServiceConfig | undefined {
  return SERVICES.find(s => s.slug === slug)
}

/** groupSlug каталога → услуги, которые стоит предложить на странице этой группы/товара */
export function getServicesForGroup(groupSlug: string): ServiceConfig[] {
  return SERVICES.filter(s => s.groupSlugs.includes(groupSlug))
}
