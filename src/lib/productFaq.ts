import type { Product, Category } from '@/types/catalog'
import { DISC_LABEL } from './constants'

export interface FaqItem {
  q: string
  a: string
}

/**
 * Универсальный FAQ-блок для карточки товара (все 6000+ товаров).
 *
 * Персональные FAQ под каждый товар нецелесообразны (см. решение по
 * уникальным описаниям для 6000+ товаров — то же самое ограничение), но
 * вопросы, с которыми реально сталкивается покупатель на любой товарной
 * странице — гарантия, доставка, скидка, возврат, опт — универсальны и
 * ПОЛЕЗНЫ независимо от конкретного товара. Faq буквально отображается на
 * странице (см. ProductPage.tsx) — это обязательное условие для FAQPage
 * schema, как и в остальных местах сайта (см. src/lib/faq.ts).
 *
 * Текст о гарантии намеренно без конкретных цифр (не "10-50 лет") — точный
 * срок зависит от материала и производителя, указывать выдуманную цифру
 * для всех товаров сразу было бы недостоверно.
 */
export function getProductFaq(product: Product, category: Category, price: number): FaqItem[] {
  const priceStr = price > 0 ? `${price.toLocaleString('ru-RU')} ₽` : 'по запросу'
  const brand = product.features?.['Производитель']?.trim()

  return [
    {
      q: `Какая гарантия на «${product.title}»?`,
      a: brand
        ? `Гарантия предоставляется производителем (${brand}) и зависит от конкретного материала и коллекции — точный срок указан в паспорте изделия или гарантийном талоне, который идёт с товаром. Если при получении обнаружился производственный брак или расхождение с заявленными характеристиками — свяжитесь с нами, поможем оформить гарантийное обращение к производителю или организуем замену.`
        : `Гарантия предоставляется производителем и зависит от конкретного материала — точный срок указан в документах на товар. Если при получении обнаружился брак — свяжитесь с нами, поможем оформить гарантийное обращение или организуем замену.`,
    },
    {
      q: 'Сколько стоит доставка и в какие сроки?',
      a: `Доставка по Московской области — от 1 до 3 рабочих дней, стоимость от 1 500 ₽ и уточняется при оформлении заказа в зависимости от адреса и объёма. Самовывоз бесплатный со склада в Новохаритонове (Раменский округ), работаем Пн–Пт 9:00–18:00, Сб 9:00–15:00.`,
    },
    {
      q: `Действует ли скидка ${DISC_LABEL} на этот товар?`,
      a: `Да, скидка ${DISC_LABEL} уже учтена в цене ${priceStr}. Дополнительная скидка −5% действует при оплате картой лояльности PLATFORMA — оформляется бесплатно при первом заказе.`,
    },
    {
      q: 'Можно ли вернуть товар, если он не подошёл?',
      a: 'Да, в течение 14 дней с момента покупки при сохранении товарного вида, упаковки и потребительских свойств — в соответствии с законом «О защите прав потребителей». Материалы, порезанные или изготовленные под индивидуальный заказ, возврату и обмену не подлежат — уточняйте у менеджера до оформления.',
    },
    {
      q: 'Можно ли купить оптом или для юридического лица?',
      a: `Да, работаем с оптовыми объёмами и с юридическими лицами — выставляем счета, работаем с НДС. Цена «${category.name}» может быть скорректирована при большом объёме заказа — уточните у менеджера по телефону.`,
    },
  ]
}
