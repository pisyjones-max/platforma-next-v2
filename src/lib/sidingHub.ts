export function getSidingOptions(catalog: Catalog) {
  return OPTIONS_CONFIG.map(opt => {
    const cat = findCategory(catalog, opt.categorySlug)
    const count = cat?.products.length ?? 0
    const prices = (cat?.products ?? [])
      .map(p => p.variants?.[0]?.price)
      .filter((p): p is number => typeof p === 'number' && p > 0)
    const minPrice = prices.length ? salePrice(Math.min(...prices)) : null
    return {
      ...opt,
      url: `/catalog/${opt.categorySlug}`,
      productCount: count,
      minPrice,
    }
  })
}

